var startersCumul []float64

func init() {
	// Вычисляем кумулятивные вероятности для всех биграммных переходов
	for _, transitions := range bigramTransitions {
		sum := 0.0
		for i := range transitions {
			sum += transitions[i].prob
			transitions[i].cumul = sum
		}
		for i := range transitions {
			transitions[i].cumul /= sum
		}
	}

	// Кумулятивные вероятности для стартовых символов
	startersCumul = make([]float64, len(starters))
	sum := 0.0
	for i, s := range starters {
		sum += s.prob
		startersCumul[i] = sum
	}
	for i := range startersCumul {
		startersCumul[i] /= sum
	}
}

// pickFromTransitions выбирает следующий символ по значению из вектора
func pickFromTransitions(transitions []struct {
	next  rune
	prob  float64
	cumul float64
}, seed float64) rune {
	r := seed
	if r > 1.0 {
		r = r - float64(int(r))
	}
	if r < 0 {
		r = -r
	}
	for _, t := range transitions {
		if r <= t.cumul {
			return t.next
		}
	}
	return transitions[len(transitions)-1].next
}

// pickStarter выбирает первый символ фразы
func pickStarter(seed float64) rune {
	r := seed
	if r > 1.0 {
		r = r - float64(int(r))
	}
	if r < 0 {
		r = -r
	}
	for i, cp := range startersCumul {
		if r <= cp {
			return starters[i].char
		}
	}
	return 'п'
}

func vectorToText(vector []float64) string {
	if len(vector) == 0 {
		return "..."
	}

	// Вычисляем длину ответа на основе энергии вектора
	sum := 0.0
	for _, v := range vector {
		sum += v
	}
	length := int(sum/float64(len(vector))*20.0) + 3
	if length < 3 {
		length = 3
	}
	if length > 30 {
		length = 30
	}

	var result strings.Builder

	// Используем вектор как источник случайности для марковской цепи
	// Первый символ — из стартеров
	seedIdx := 0
	seed := vector[seedIdx%len(vector)]
	if seed < 0 {
		seed = -seed
	}
	currentChar := pickStarter(seed)
	result.WriteRune(currentChar)

	// Строим цепочку по биграммам
	for i := 1; i < length; i++ {
		transitions, exists := bigramTransitions[currentChar]
		if !exists || len(transitions) == 0 {
			// Такого символа нет в таблице — начинаем заново
			seedIdx++
			seed = vector[seedIdx%len(vector)]
			if seed < 0 {
				seed = -seed
			}
			currentChar = pickStarter(seed)
			result.WriteRune(currentChar)
			continue
		}

		// Выбираем следующий символ из переходов
		seedIdx++
		s := vector[seedIdx%len(vector)]
		if s < 0 {
			s = -s
		}
		currentChar = pickFromTransitions(transitions, s)
		result.WriteRune(currentChar)
	}

	return strings.TrimSpace(result.String())
}

func sqrt(x float64) float64 {
	if x <= 0 {
		return 0
	}
	z := x
	for i := 0; i < 20; i++ {
		z -= (z*z - x) / (2 * z)
	}
	return z
}

func cosineSimilarity(a, b []float64) float64 {
	if len(a) != len(b) || len(a) == 0 {
		return 0
	}
	var dot, normA, normB float64
	for i := range a {
		dot += a[i] * b[i]
		normA += a[i] * a[i]
		normB += b[i] * b[i]
	}
	if normA == 0 || normB == 0 {
		return 0
	}
	return dot / (sqrt(normA) * sqrt(normB))
}