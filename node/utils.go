package main

import (
	"crypto/sha256"
	"fmt"
	"strings"
	"time"
)

const VectorDim = 100

func hashText(text string) string {
	h := sha256.Sum256([]byte(text))
	return fmt.Sprintf("%x", h[:8])
}

func generateMsgID(text string) string {
	data := text + time.Now().String()
	h := sha256.Sum256([]byte(data))
	return fmt.Sprintf("%x", h[:8])
}

func hashToVector(hash string) []float64 {
	vec := make([]float64, VectorDim)
	for i, ch := range hash {
		if i >= VectorDim {
			break
		}
		vec[i] = float64(ch) / 255.0
	}
	return vec
}

func textToVector(text string) []float64 {
	vec := make([]float64, VectorDim)
	text = strings.ToLower(text)

	for i, ch := range text {
		vec[i%VectorDim] += float64(ch) * 0.3
	}

	for i := 0; i < len(text)-1; i++ {
		bigram := text[i : i+2]
		h := sha256.Sum256([]byte(bigram))
		for j := 0; j < VectorDim; j++ {
			vec[j] += float64(h[j%len(h)]) / 255.0 * 0.7
		}
	}

	max := 0.0
	for _, v := range vec {
		if v > max {
			max = v
		}
	}
	if max > 0 {
		for i := range vec {
			vec[i] = vec[i] / max
			if vec[i] > 1.0 {
				vec[i] = 1.0
			}
		}
	}
	return vec
}

